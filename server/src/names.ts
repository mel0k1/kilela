const FIRST = [
  'Искорка', 'Плюшка', 'Тучка', 'Звёздочка', 'Ромашка', 'Пиратка', 'Вишенка', 'Тучность',
  'Сахарок', 'Мятница', 'Огонёк', 'Пушинка', 'Карамелька', 'Лунница', 'Яблонька', 'Соня',
  'Бусинка', 'Тропинка', 'Печенюшка', 'Свистулька', 'Смельчак', 'Тихоня', 'Шалун', 'Пончик',
];

const LAST = [
  'из Долины', 'Северная', 'Быстрокопытная', 'Улыбчивая', 'Запоздалая', 'Облачная',
  'Серебристая', 'Тёплая', 'Вечерняя', 'Солнцеликая', 'Мятная', 'Задорная',
];

export function randomName(): string {
  const a = FIRST[Math.floor(Math.random() * FIRST.length)];
  const r = Math.random();

  if (r < 0.35) {
    const b = LAST[Math.floor(Math.random() * LAST.length)];
    return `${a} ${b}`;
  }

  return a;
}
